/** 每个分类最多保留的条目数，保证 40~120 的区间要求。 */
export const EMOJI_PER_CATEGORY = 120;

/** 笑脸与人物合并成一类；按比例交错取，避免某一类把另一类挤掉。 */
const SMILEYS_MERGED: Row[] = interleave(SMILEYS, PEOPLE);

function interleave(left: Row[], right: Row[]): Row[] {
  const total = left.length + right.length;
  const leftQuota = Math.round((left.length / total) * EMOJI_PER_CATEGORY);
  const rightQuota = EMOJI_PER_CATEGORY - leftQuota;
  const picked: Row[] = [];
  for (let i = 0; i < Math.max(leftQuota, rightQuota); i++) {
    if (i < leftQuota) picked.push(left[i] as Row);
    if (i < rightQuota) picked.push(right[i] as Row);
  }
  return picked;
}

const CATEGORY_ROWS: Record<string, Row[]> = {
  smileys: SMILEYS_MERGED,
  animals: ANIMALS,
  food: FOOD,
  travel: TRAVEL,
  activities: ACTIVITIES,
  objects: OBJECTS,
  symbols: SYMBOL_ROWS,
  flags: FLAGS,
};

function buildCategory(id: string): EmojiItem[] {
  const rows = CATEGORY_ROWS[id] ?? [];
  const seen = new Set<string>();
  const items: EmojiItem[] = [];
  for (const [char, name, zh, shortcode] of rows) {
    // 同名 shortcode 只保留首个 emoji（旗帜类别里存在重复条目）
    const key = `${char}:${shortcode}`;
    if (seen.has(key)) continue;
    seen.add(key);
    items.push({ char, name, zh, shortcode, category: id });
    // 分类内去重后仍按上限截断，保证每类条目数落在 40~120
    if (items.length >= EMOJI_PER_CATEGORY) break;
  }
  return items;
}

export const EMOJIS: EmojiItem[] = EMOJI_CATEGORIES.flatMap((category) => buildCategory(category.id));

export const EMOJI_TOTAL = EMOJIS.length;

/** Unicode 码点列表，如 [1F600]。 */
export function codePoints(char: string): string[] {
  return [...char].map((c) => `U+${(c.codePointAt(0) ?? 0).toString(16).toUpperCase().padStart(4, '0')}`);
}

/** UTF-16 code unit 长度。 */
export function utf16Length(char: string): number {
  return char.length;
}

/** 是否含有肤色修饰符（U+1F3FB ~ U+1F3FF）。 */
export function hasSkinTone(char: string): boolean {
  for (const c of char) {
    const cp = c.codePointAt(0) ?? 0;
    if (cp >= 0x1f3fb && cp <= 0x1f3ff) return true;
  }
  return false;
}

/** 是否为 ZWJ 序列（含 U+200D）。 */
export function isZwjSequence(char: string): boolean {
  return char.includes('‍');
}

/** 是否含变体选择符（U+FE0F）。 */
export function hasVariantSelector(char: string): boolean {
  return char.includes('️');
}

/** 是否为区域指示符对组成的国旗。 */
export function isRegionalIndicatorPair(char: string): boolean {
  const points = [...char].map((c) => c.codePointAt(0) ?? 0);
  return points.length === 2 && points.every((cp) => cp >= 0x1f1e6 && cp <= 0x1f1ff);
}

/** 字符 → 所有码点的十进制形式，用于 &#128512; 输出。 */
export function decimalEntities(char: string): string {
  return [...char].map((c) => `&#${c.codePointAt(0) ?? 0};`).join('');
}

/** 字符 → 所有码点的十六进制形式，用于 &#x1F600; 输出。 */
export function hexEntities(char: string): string {
  return [...char].map((c) => `&#x${(c.codePointAt(0) ?? 0).toString(16).toUpperCase()};`).join('');
}

export function shortcode(char: string): string {
  return EMOJIS.find((item) => item.char === char)?.shortcode ?? '';
}

export interface EmojiFilter {
  query: string;
  category: string;
  skinOnly: boolean;
  zwjOnly: boolean;
}

/** 按关键词与分类筛选 emoji，支持中文名与 shortcode。 */
export function filterEmojis({ query, category, skinOnly, zwjOnly }: EmojiFilter): EmojiItem[] {
  const q = query.trim().toLowerCase();
  return EMOJIS.filter((item) => {
    if (category !== 'all' && item.category !== category) return false;
    if (skinOnly && !hasSkinTone(item.char)) return false;
    if (zwjOnly && !isZwjSequence(item.char)) return false;
    if (!q) return true;
    return (
      item.name.toLowerCase().includes(q) ||
      item.zh.includes(q) ||
      item.shortcode.toLowerCase().includes(q) ||
      item.char.includes(q)
    );
  });
}

