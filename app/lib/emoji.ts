export function filterSymbols(query: string, group: string): SymbolItem[] {
  const q = query.trim().toLowerCase();
  return SYMBOLS.filter((item) => {
    if (group !== '全部' && item.group !== group) return false;
    if (!q) return true;
    return (
      item.char === query ||
      item.name.toLowerCase().includes(q) ||
      item.zh.toLowerCase().includes(q) ||
      item.entity.toLowerCase().includes(q) ||
      item.code.toLowerCase().includes(q)
    );
  });
}

/** HTML 实体查询：支持按名称（&amp;）、字符或数值查询。 */
export function queryEntities(query: string, limit = 40): SymbolItem[] {
  const raw = query.trim();
  if (!raw) return [];
  const cleaned = raw.replace(/^&/, '').replace(/;$/, '');
  if (/^#x[0-9a-f]+$/i.test(cleaned)) {
    const code = Number.parseInt(cleaned.slice(2), 16);
    const char = String.fromCodePoint(code);
    const existing = SYMBOLS.find((item) => item.char === char);
    return existing ? [existing] : [];
  }
  if (/^#\d+$/.test(cleaned)) {
    const code = Number.parseInt(cleaned.slice(1), 10);
    if (code <= 0 || code > 0x10ffff) return [];
    const char = String.fromCodePoint(code);
    const existing = SYMBOLS.find((item) => item.char === char);
    return existing ? [existing] : [];
  }
  const q = cleaned.toLowerCase();
  return SYMBOLS.filter((item) => item.entity.toLowerCase() === q || item.name.toLowerCase() === q).slice(0, limit);
}

export function entityFor(item: SymbolItem): string {
  return item.entity ? `&${item.entity};` : '';
}

export function numericEntityFor(char: string): string {
  return [...char].map((c) => `&#${c.codePointAt(0) ?? 0};`).join('');
}
